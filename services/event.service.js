const path = require("path");
const FILE = path.basename(__filename).split(".js")[0].toUpperCase();

var fs = require("fs").promises;
const validator = require("validator");

const {
  ExError,
  STATUS_CODE,
  INTERNAL_ERRORS,
} = require("../middleware/errorHandler");
const uuid = require("uuid");

let EVENTS = [];

function sanitizeInput(input) {
  if (typeof input !== "string") return input;

  // Escape HTML and trim whitespace
  return validator.escape(input.trim());
}

async function get(text, tags, begin, end, beginText, endText) {
  logger.info(`[${FILE}] get called`);

  // Sanitize string inputs
  if (text) text = sanitizeInput(text);
  if (tags) tags = sanitizeInput(tags);
  if (beginText) beginText = sanitizeInput(beginText);
  if (endText) endText = sanitizeInput(endText);

  tags = tags ? tags.split(",").map((tag) => tag.trim()) : [];

  if (beginText) {
    let events = EVENTS.filter((event) => event.text.includes(beginText)).sort(
      function (e1, e2) {
        return e1.year - e2.year;
      }
    );
    if (events.length > 0) begin = events[0].year;
  }
  if (endText) {
    let events = EVENTS.filter((event) => event.text.includes(endText)).sort(
      function (e1, e2) {
        return e2.year - e1.year;
      }
    );
    if (events.length > 0) end = events[0].year;
  }

  // Tags filter on the event's own stored tags (person names) — this used to
  // also infer a begin/end year range and annotate each match with the
  // tagged person's age via member.service, but that cross-service lookup
  // went away once members moved to their own app (see FamTree). Plain
  // substring matching on the event's tags is what's left.
  let events = EVENTS.filter((event) => {
    if (begin && event.year < begin) return false;
    if (end && event.year > end) return false;
    if (text && !event.text.includes(text)) return false;
    if (
      tags.length &&
      !tags.some((tag) => (event.tags || []).some((t) => t.includes(tag)))
    )
      return false;
    return true;
  })
    .map((event) => ({ ...event }))
    .sort(function (e1, e2) {
      return e1.year - e2.year;
    });

  return { count: events.length, data: events };
}

async function add(params) {
  logger.info(`[${FILE}] add called`);

  // Sanitize string inputs
  if (params.text) {
    params.text = sanitizeInput(params.text);
  }

  // Validate required fields
  if (
    params.year === undefined ||
    params.year === null ||
    typeof params.year !== "number"
  ) {
    logger.error(`[${FILE}] invalid year parameter: ${params.year}`);
    throw new ExError(
      STATUS_CODE.CLIENT_ERROR,
      "Year is required and must be a number"
    );
  }

  // Validate year range (allowing 0 for Creation)
  if (params.year < 0 || params.year > 10000) {
    logger.error(`[${FILE}] invalid year range: ${params.year}`);
    throw new ExError(
      STATUS_CODE.CLIENT_ERROR,
      "Year must be between 0 and 10000"
    );
  } // Validate text length if provided
  if (params.text && params.text.length > 500) {
    logger.error(`[${FILE}] text too long: ${params.text.length} characters`);
    throw new ExError(
      STATUS_CODE.CLIENT_ERROR,
      "Event text must be less than 500 characters"
    );
  }

  // Sanitize references array if provided
  if (params.references && Array.isArray(params.references)) {
    params.references = params.references.map((ref) => sanitizeInput(ref));
  }

  let events = EVENTS.filter((event) => {
    if (event.text === params.text && event.year === params.year) return event;
  });
  if (events.length > 0) {
    logger.error(`[${FILE}] existing event exists`);
    throw new ExError(
      STATUS_CODE.CLIENT_ERROR,
      INTERNAL_ERRORS.DUPLIACTE_EVENT
    );
  }

  if (!params.uuid) params.uuid = uuid.v4();

  EVENTS.push(params);

  return await params;
}

async function load() {
  logger.info(`[${FILE}] load called`);

  // events.json is our own trusted store: load it verbatim. Running it through
  // add() re-escaped every string on each startup (" -> &quot; -> &amp;quot;...).
  let data = [];
  try {
    data = JSON.parse(await fs.readFile(DATA_FILE, "utf8"));
  } catch (err) {
    if (err.code !== "ENOENT") throw err;
    logger.warn(`[${FILE}] ${DATA_FILE} not found - starting with no events`);
  }
  const seen = new Set();
  for (let event of data) {
    const key = event.year + "|" + event.text;
    if (seen.has(key)) continue;
    seen.add(key);
    if (!event.uuid) event.uuid = uuid.v4();
    EVENTS.push(event);
  }
  logger.info(`[${FILE}] loaded ${EVENTS.length} events`);
}

async function dump() {
  logger.info(`[${FILE}] dump called`);

  // Keep every field (memberUuid / eventType / autoGenerated link births to
  // deaths) — the old whitelist silently dropped them on every add.
  let json = EVENTS.map((event) => ({ ...event }));

  await fs.writeFile(DATA_FILE, JSON.stringify(json, null, 2), "utf8");
}

async function getAllEvents() {
  logger.info(`[${FILE}] getAllEvents called`);
  return EVENTS.map((event) => {
    return {
      year: event.year,
      text: event.text,
      tags: event.tags,
      references: event.references,
      uuid: event.uuid,
    };
  });
}

module.exports = {
  get,
  add,
  load,
  dump,
  getAllEvents,
};
