const FILE = "ROUTER";

const express = require("express");
const cors = require("cors");
const path = require("path");
const rateLimit = require("express-rate-limit");
const helmet = require("helmet");
const { initLogger } = require("../tools/logger");
const mlogger = require("../middleware/logger");
const {
  errorHandler,
  ExError,
  STATUS_CODE,
  INTERNAL_ERRORS,
} = require("../middleware/errorHandler");

const { Router } = require("./route");
let router = new Router();

// Security middleware
router.use(
  helmet({
    contentSecurityPolicy: {
      directives: {
        defaultSrc: ["'self'"],
        styleSrc: ["'self'", "'unsafe-inline'", "https://cdnjs.cloudflare.com", "https://fonts.googleapis.com"],
        scriptSrc: ["'self'", "'unsafe-inline'"],
        scriptSrcAttr: ["'unsafe-inline'"], // Allow inline event handlers like onclick
        fontSrc: ["'self'", "https://cdnjs.cloudflare.com", "https://fonts.gstatic.com"],
        // Served over plain http (also to the phone via LAN IP / Tailscale);
        // helmet's default would rewrite this page's fetch() calls to https.
        upgradeInsecureRequests: null,
      },
    },
    strictTransportSecurity: false,
  })
);

// Rate limiting is a production concern only; skip it in dev so local testing isn't throttled
const isDev = process.env.NODE_ENV !== "production";

// trust proxy is configured once at the app level (server.js) — newer
// express-rate-limit versions reject a redundant per-limiter trustProxy option.
const limiter = rateLimit({
  windowMs: 15 * 60 * 1000, // 15 minutes
  max: 100, // limit each IP to 100 requests per windowMs
  skip: () => isDev,
  message: {
    error: "Too many requests from this IP, please try again later.",
  },
  standardHeaders: true,
  legacyHeaders: false,
});
router.use(limiter);

// Stricter rate limiting for POST requests
const strictLimiter = rateLimit({
  windowMs: 15 * 60 * 1000, // 15 minutes
  max: 20, // limit each IP to 20 POST requests per windowMs
  skip: (req) => isDev || req.method !== "POST",
  message: {
    error:
      "Too many modification requests from this IP, please try again later.",
  },
});
router.use(strictLimiter);

router.use(cors());
router.use(express.urlencoded({ extended: true, limit: "10mb" }));
router.use(express.json({ limit: "10mb" }));

router.use(initLogger);
router.use(mlogger.addReqIdToLog);
router.use(mlogger.reqInfo);

router.subroute("/events", require("./event.routes"));

// Serve HTML interfaces
router.route({
  topic: "",
  method: "get",
  name: "Main Interface",
  route: "/",
  cbs: [
    (req, res) => {
      sendPage(res, "events.html");
    },
  ],
  authorization: false,
});

router.route({
  topic: "",
  method: "get",
  name: "Events Interface",
  route: "/events",
  cbs: [
    (req, res) => {
      sendPage(res, "events.html");
    },
  ],
  authorization: false,
});

// App icons (generated by dashboard/icons/make_icons.py)
for (const [route, file, type] of [
  ["/favicon.svg", "favicon.svg", "image/svg+xml"],
  ["/apple-touch-icon.png", "apple-touch-icon.png", "image/png"],
]) {
  router.route({
    topic: "",
    method: "get",
    name: "Icon " + file,
    route,
    cbs: [
      (req, res) => {
        res.type(type).set("Cache-Control", "public, max-age=86400");
        res.sendFile(path.join(__basedir, "services", file));
      },
    ],
    authorization: false,
  });
}

// Handle favicon requests to prevent error logs
router.route({
  topic: "",
  method: "get",
  name: "Favicon",
  route: "/favicon.ico",
  cbs: [
    (req, res) => {
      res.status(204).send(); // No Content response for favicon
    },
  ],
  authorization: false,
});

router.use((req, res, next) => {
  logger.error(`[${FILE}] invalid API`);
  next(new ExError(STATUS_CODE.CLIENT_ERROR, INTERNAL_ERRORS.INVALID_API));
});

// must be last
router.use(errorHandler);

module.exports = router;

// Serve a UI page with the API token from .env filled in (never hard-coded in the file).
function sendPage(res, file) {
  const html = require("fs")
    .readFileSync(path.join(__basedir, "services", file), "utf8")
    .replace("'__API_TOKEN__'", JSON.stringify(process.env.API_TOKEN || ""));
  res.type("html").set("Cache-Control", "no-store").send(html);
}
